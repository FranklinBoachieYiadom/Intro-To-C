#include <stdio.h>
#include <stdlib.h>
#include <math.h>


int main(){
 //These are for for loops

 //This is for increamenting from 1 to 10
    int x;
    for(x=1; x<=10; x++){
        printf("%i\n",x);
    }

    printf("\n");
    
//This is for decrementing from 10 to 1
    for (x=10; x>=1; x--){
        printf("%i\n" ,x);
    } 
    return 0;
}

